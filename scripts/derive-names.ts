/**
 * Derives the people/places list from STEPBible's TIPNR ("Translators Individualised Proper
 * Names with all References", Tyndale House / STEPBible.org, CC BY 4.0).
 *
 * The original file is not redistributed (STEPBible asks that copies are not posted elsewhere);
 * only this derived subset is committed: unique name, type, short description and the verses
 * where the individual/place is named.
 *
 *   node scripts/derive-names.ts [path/to/TIPNR.txt]
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { BOOKS, osisId, verseIndex } from '../src/data/bibleStructure.ts';

const URL_TIPNR =
  'https://raw.githubusercontent.com/STEPBible/STEPBible-Data/master/Proper%20Nouns/TIPNR%20-%20Translators%20Individualised%20Proper%20Names%20with%20all%20References%20-%20STEPBible.org%20CC%20BY.txt';
const OUT = 'data-source/names/tipnr-derived.json';

/** STEPBible book abbreviations → OSIS codes used by the app. */
const STEP: Record<string, string> = {
  Gen: 'Gen', Exo: 'Exod', Lev: 'Lev', Num: 'Num', Deu: 'Deut', Jos: 'Josh', Jdg: 'Judg', Rut: 'Ruth', '1Sa': '1Sam', '2Sa': '2Sam',
  '1Ki': '1Kgs', '2Ki': '2Kgs', '1Ch': '1Chr', '2Ch': '2Chr', Ezr: 'Ezra', Neh: 'Neh', Est: 'Esth', Job: 'Job', Psa: 'Ps', Pro: 'Prov',
  Ecc: 'Eccl', Sng: 'Song', Isa: 'Isa', Jer: 'Jer', Lam: 'Lam', Ezk: 'Ezek', Dan: 'Dan', Hos: 'Hos', Jol: 'Joel', Amo: 'Amos',
  Oba: 'Obad', Jon: 'Jonah', Mic: 'Mic', Nam: 'Nah', Hab: 'Hab', Zep: 'Zeph', Hag: 'Hag', Zec: 'Zech', Mal: 'Mal',
  Mat: 'Matt', Mrk: 'Mark', Luk: 'Luke', Jhn: 'John', Act: 'Acts', Rom: 'Rom', '1Co': '1Cor', '2Co': '2Cor', Gal: 'Gal', Eph: 'Eph',
  Php: 'Phil', Col: 'Col', '1Th': '1Thess', '2Th': '2Thess', '1Ti': '1Tim', '2Ti': '2Tim', Tit: 'Titus', Phm: 'Phlm', Heb: 'Heb',
  Jas: 'Jas', '1Pe': '1Pet', '2Pe': '2Pet', '1Jn': '1John', '2Jn': '2John', '3Jn': '3John', Jud: 'Jude', Rev: 'Rev',
};
const BOOK_ID = new Map(BOOKS.map((b) => [b.code, b.id]));

async function main() {
  let path = process.argv[2];
  if (!path) {
    path = 'data-source/.cache/tipnr.txt';
    if (!existsSync(path)) {
      mkdirSync('data-source/.cache', { recursive: true });
      const res = await fetch(URL_TIPNR);
      if (!res.ok) throw new Error(`Download failed: ${res.status}`);
      writeFileSync(path, Buffer.from(await res.arrayBuffer()));
    }
  }
  const raw = readFileSync(path);
  const lines = raw.toString('utf8').split('\n');
  type Rec = { type: string; unique: string | null; brief: string; verses: Set<number> };
  const recs: Rec[] = [];
  let cur: Rec | null = null;
  let skipped = 0;
  for (const ln of lines) {
    if (ln.startsWith('$==========')) {
      const t = ln.split('\t')[0].replace(/[$=]/g, '').trim();
      cur = { type: t, unique: null, brief: '', verses: new Set() };
      recs.push(cur);
      continue;
    }
    if (!cur) continue;
    const cols = ln.split('\t');
    if (cur.unique === null && cols[0].includes('@') && !ln.startsWith('–') && !ln.startsWith('@')) {
      cur.unique = cols[0].trim();
      continue;
    }
    if (ln.startsWith('@Brief=')) cur.brief = ln.slice(7).split('\t')[0].trim();
    if (ln.startsWith('–') && !ln.startsWith('– Total') && cols.length > 4) {
      for (const r of cols[4].split(';')) {
        const m = /^([1-3]?[A-Za-z]+)\.(\d+)\.(\d+)[a-z]?$/.exec(r.trim());
        if (!m) continue;
        const id = BOOK_ID.get(STEP[m[1]] ?? '');
        const g = id === undefined ? -1 : verseIndex(id, Number(m[2]), Number(m[3]));
        if (g < 0) skipped++;
        else cur.verses.add(g);
      }
    }
  }
  const TYPES: Record<string, string> = { 'PERSON(s)': 'person', PLACE: 'place', 'PLACE+PERSON': 'place', OTHER: 'other' };
  const entries = recs
    .filter((r) => r.unique && !r.unique.startsWith('UnifiedName') && TYPES[r.type] && r.verses.size)
    .map((r) => [r.unique!.split('=')[0], TYPES[r.type], r.brief, [...r.verses].sort((a, b) => a - b).map(osisId).join(';')]);
  const doc = {
    source: 'TIPNR - Translators Individualised Proper Names with all References, STEPBible.org',
    license: 'CC BY 4.0 — Data created by www.STEPBible.org based on work at Tyndale House Cambridge',
    url: 'https://github.com/STEPBible/STEPBible-Data',
    sha256: createHash('sha256').update(raw).digest('hex'),
    changes:
      'Derived subset: unique name (Name@FirstReference), type (person / place / other), the "@Brief" description and the verses where the name occurs (sub-letters a/b merged). References outside the KJV versification are skipped. Generated by scripts/derive-names.ts.',
    skippedReferences: skipped,
    entries,
  };
  writeFileSync(OUT, JSON.stringify(doc).replace(/\],\[/g, '],\n['));
  console.log(`Wrote ${OUT}: ${entries.length} names, ${entries.reduce((a, e) => a + (e[3] as string).split(';').length, 0)} verse occurrences, ${skipped} references skipped`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
